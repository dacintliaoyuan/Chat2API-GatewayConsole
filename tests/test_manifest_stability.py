# -*- coding: utf-8 -*-
"""Manifest stability: local tool state must not drift ``deployment_files``.

``make-manifest.py`` freezes the release closure from the CURRENT bytes on this
machine, and this checkout is also where local tooling writes its own state: the
``.mimosa`` hooks rewrite ``.mimosa/hook-state`` and ``.mimosa/hook-status`` on
every run.  Those directories are git-ignored and are not deployment material, so
listing them would change ``deployment_files`` (and make ``--check`` return 65)
without a single product byte changing.

The tests build a throw-away deployment tree instead of reading the real one, so they
stay valid while the release materials themselves are edited.
"""

import importlib.util
import json
import sys
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest import mock

MANIFEST_SCRIPT = (Path(__file__).resolve().parents[1]
                   / "um-cloud-deploy" / "make-manifest.py")
SPEC = importlib.util.spec_from_file_location(
    "um_cloud_make_manifest", MANIFEST_SCRIPT)
make_manifest = importlib.util.module_from_spec(SPEC)
assert SPEC.loader is not None
sys.modules[SPEC.name] = make_manifest
SPEC.loader.exec_module(make_manifest)

DEPLOY_REL = "um-cloud-deploy"

# Files that really ship: scripts, units, config examples, brokerctl, README.
REAL_MATERIALS = [
    "README.md",
    "install.sh",
    "update.sh",
    "rollback.sh",
    "lib/common.sh",
    "bin/um-share-gatewayctl.py",
    "systemd/um-share-broker.service",
    "systemd/um-share-console.service",
    "systemd/um-share-display.service",
    "config/broker.env.example",
    "config/um-share.json.example",
    "Caddyfile.example",
]

# Local tool state: written by hooks and test runs, git-ignored, never shipped.
LOCAL_STATE_FILES = [
    ".mimosa/hook-state/sess-a.json",
    ".mimosa/hook-state/sess-a.baseline/deadbeef.source",
    ".mimosa/hook-status/sess-a-1.json",
    ".pytest_cache/CACHEDIR.TAG",
    ".mypy_cache/3.14/x.json",
    ".ruff_cache/content",
    "__pycache__/make-manifest.cpython-314.pyc",
    "stale.pyc",
]

# Regenerated by make-manifest.py/package-release.sh, never inputs.
GENERATED_FILES = ["RELEASE-MANIFEST.json", "SHA256SUMS"]


def _write(root: Path, rel: str, text: str = "x\n") -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


class DeploymentFilesStabilityTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        self.deploy_root = self.root / DEPLOY_REL
        for rel in REAL_MATERIALS + LOCAL_STATE_FILES + GENERATED_FILES:
            _write(self.deploy_root, rel)

    def _paths(self) -> list[str]:
        return [entry["path"] for entry in
                make_manifest._deployment_files(self.root, self.deploy_root)]

    def _expected(self) -> list[str]:
        return sorted(DEPLOY_REL + "/" + rel for rel in REAL_MATERIALS)

    def test_deployment_files_keep_only_real_materials(self):
        self.assertEqual(self._expected(), sorted(self._paths()))

    def test_no_local_state_dir_survives_at_any_depth(self):
        nested = "config/.mimosa/hook-state/nested.json"
        _write(self.deploy_root, nested)
        paths = self._paths()
        self.assertNotIn(DEPLOY_REL + "/" + nested, paths)
        for path in paths:
            for part in Path(path).parts:
                self.assertNotIn(part, make_manifest.LOCAL_STATE_DIRS, path)

    def test_hook_writes_do_not_change_deployment_files(self):
        before = self._paths()
        # A hook run appends a session file, its baseline snapshot and a status
        # record; the manifest must stay byte-for-byte identical.
        _write(self.deploy_root, ".mimosa/hook-state/sess-b.json", "{}\n")
        _write(self.deploy_root,
               ".mimosa/hook-state/sess-b.baseline/abcdef.source", "y\n")
        _write(self.deploy_root, ".mimosa/hook-status/sess-b-2.json", "{}\n")
        self.assertEqual(before, self._paths())

    def test_manifest_field_uses_the_filtered_list(self):
        lock = self.root / "dependencies.lock.json"
        lock.write_text(json.dumps({"target": {"python": "3.14"}}),
                        encoding="utf-8")
        for rel in make_manifest.CLOUD_RUNTIME:
            _write(self.root, rel)
        args = SimpleNamespace(
            root=self.root,
            deploy_root=self.deploy_root,
            version="test-1",
            dependencies=lock,
            web_dist=None,
            allow_missing_web=True,
            require_web_role=None,
        )
        # The product closure is orthogonal here: the stub files exist so that
        # ``_files`` can hash them, and the static superset is pinned to the
        # explicit cloud runtime list.
        with mock.patch.object(make_manifest, "_closure",
                               return_value=sorted(make_manifest.CLOUD_RUNTIME)):
            manifest = make_manifest._build(args)
        paths = [entry["path"] for entry in manifest["deployment_files"]]
        self.assertEqual(self._expected(), sorted(paths))
        self.assertEqual({"deployment"},
                         {entry["kind"] for entry in manifest["deployment_files"]})


class WebDistBindingTests(unittest.TestCase):
    """The carried console tree is bound to its role and entry chunk.

    A cloud release must not carry the local-role tree: the manifest records the
    role from ``candidate-build.json`` and the module script ``index.html``
    loads, and ``--require-web-role`` refuses a tree built for another role.
    """

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        self.deploy_root = self.root / DEPLOY_REL
        for rel in REAL_MATERIALS:
            _write(self.deploy_root, rel)
        self.dist = self.root / "web" / "release" / "candidate" / "cloud"
        _write(self.dist, "assets/index-abc.js")
        _write(self.dist, "index.html",
               '<script type="module" crossorigin src="/assets/index-abc.js">'
               "</script>\n")
        _write(self.dist, "candidate-build.json", json.dumps({
            "line": "candidate-cloud", "mode": "candidate-cloud",
            "role": "cloud", "entryAssets": ["assets/index-abc.js"],
        }))

    def _args(self, **changes):
        lock = self.root / "dependencies.lock.json"
        lock.write_text(json.dumps({"target": {"python": "3.14"}}),
                        encoding="utf-8")
        for rel in make_manifest.CLOUD_RUNTIME:
            _write(self.root, rel)
        values = {
            "root": self.root, "deploy_root": self.deploy_root,
            "version": "test-1", "dependencies": lock,
            "web_dist": self.dist, "allow_missing_web": False,
            "require_web_role": None,
            "require_web_line": None,
        }
        values.update(changes)
        return SimpleNamespace(**values)

    def _build(self, **changes):
        with mock.patch.object(make_manifest, "_closure",
                               return_value=sorted(make_manifest.CLOUD_RUNTIME)):
            return make_manifest._build(self._args(**changes))

    def test_manifest_records_the_console_role_and_entry(self):
        manifest = self._build(require_web_role="cloud")
        web = manifest["web_dist"]
        self.assertTrue(web["included"])
        self.assertEqual("web/release/candidate/cloud", web["root"])
        self.assertEqual("cloud", web["build"]["role"])
        self.assertEqual("assets/index-abc.js", web["entry"])
        paths = {entry["path"] for entry in web["files"]}
        self.assertIn("web/release/candidate/cloud/assets/index-abc.js", paths)

    def test_local_tree_is_refused_for_a_cloud_release(self):
        _write(self.dist, "candidate-build.json", json.dumps({
            "line": "candidate-local", "role": "local",
            "entryAssets": ["assets/local-console-xyz.js"],
        }))
        with self.assertRaises(SystemExit):
            self._build(require_web_role="cloud")

    def test_a_candidate_line_is_refused_for_a_release_payload(self):
        # usagesrv.py answers 500 for every line other than production, so a
        # candidate preview tree must not be packaged as a deployable release.
        with self.assertRaises(SystemExit):
            self._build(require_web_line="production")

    def test_a_production_line_is_accepted_for_a_release_payload(self):
        _write(self.dist, "candidate-build.json", json.dumps({
            "line": "production", "mode": "production",
            "role": "cloud", "sourceHash": "a" * 64,
            "entryAssets": ["assets/index-abc.js"],
        }))
        manifest = self._build(require_web_line="production")
        self.assertEqual("production", manifest["web_dist"]["build"]["line"])
        self.assertEqual("cloud", manifest["web_dist"]["build"]["role"])

    def test_required_role_needs_a_console_tree(self):
        with self.assertRaises(SystemExit):
            self._build(web_dist=None, allow_missing_web=True,
                         require_web_role="cloud")


if __name__ == "__main__":
    unittest.main()
