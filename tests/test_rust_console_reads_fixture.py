# -*- coding: utf-8 -*-
"""Rust S5b console read-face fixture freshness (Ticket #52).

`tests/fixtures/rust_console_reads_rev1.json` must be generated by
`tests/generate_rust_console_reads_fixture.py` from the real Python cloud
`usagesrv.Handler`. This module only starts loopback temporary servers and
temporary directories; it never binds a production port or reads production data.
"""

import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests" / "fixtures" / "rust_console_reads_rev1.json"

sys.path.insert(0, str(ROOT / "tests"))


class RustConsoleReadsFixtureTests(unittest.TestCase):
    def test_fixture_is_fresh_from_the_real_python_cloud_console(self):
        import generate_rust_console_reads_fixture as generator

        self.assertEqual(
            generator.main(),
            json.loads(FIXTURE.read_text(encoding="utf-8")),
            "Rust console reads fixture is stale; run "
            "python tests/generate_rust_console_reads_fixture.py",
        )

    def test_fixture_records_every_acceptance_surface(self):
        fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
        self.assertTrue(fixture["metadata"]["fixture"])
        self.assertEqual(fixture["shareStatus"]["cases"]["confirmedRunning"]
                         ["body"]["gateway_running"], True)
        self.assertEqual(fixture["shareStatus"]["cases"]["confirmedStopped"]
                         ["body"]["gateway_running"], False)
        self.assertNotIn("gateway_running",
                         fixture["shareStatus"]["cases"]["unconfirmed"]["body"])
        self.assertEqual(len(fixture["shareKeys"]["body"]["keys"]), 6)
        outcomes = fixture["shareSecret"]
        self.assertEqual(outcomes["plaintext"]["status"], 200)
        self.assertIn("secret", outcomes["plaintext"]["body"])
        self.assertEqual(outcomes["legacy"]["body"]["reason"], "legacy")
        self.assertEqual(
            outcomes["undecryptable"]["body"]["reason"], "undecryptable")
        self.assertEqual(
            outcomes["versionConflict"]["body"]["reason"], "version_conflict")
        self.assertEqual(outcomes["deleted"]["status"], 410)
        self.assertEqual(outcomes["unknown"]["status"], 404)
        usage = fixture["shareUsage"]
        self.assertTrue(usage["ledger"])
        self.assertEqual(
            usage["summary"]["all"]["coverage"]["records"], 10)
        self.assertEqual(
            usage["summary"]["all"]["coverage"]["keyNames"], 3)
        self.assertEqual(
            usage["summary"]["all"]["results"]["unknown"], 1)
        self.assertIsNone(
            usage["summary"]["all"]["unattributed"]
            ["tokenUsage"]["totalTokens"])
        self.assertEqual(
            usage["http"]["invalidWindow"]["status"], 400)
        self.assertEqual(
            usage["requests"]["limit2"]["nextCursor"], "9")
        self.assertEqual(
            usage["http"]["requestsInvalidCursor"]["status"], 400)
        self.assertEqual(
            fixture["ac4"]["cloudOps"]["valid"]["security"]["records"], 2)
        self.assertEqual(
            fixture["ac4"]["cloudOps"]["valid"]["security"]["pending_remote"], 1)
        self.assertEqual(
            fixture["ac4"]["displaySession"]["reason"], "display_disabled")
        self.assertEqual(
            fixture["ac4"]["displayStates"]["manual"]["state"], "failed")
        self.assertEqual(len(fixture["capabilityExplicit"]), 14)
        for case in fixture["capabilityExplicit"].values():
            self.assertEqual(case["status"], 503)
            self.assertEqual(case["body"]["error"], "capability_not_assembled")
        share = fixture["apiShare"]
        self.assertEqual(share["control.status"]["status"], 200)
        self.assertEqual(share["session.keys"]["status"], 200)
        self.assertEqual(
            share["control.secret"]["body"]["secret"],
            "um-share-alpha-0123456789abcdef")
        self.assertEqual(share["control.operation"]["body"]["operation_id"], "op-1")
        self.assertEqual(share["noCredentials"]["status"], 401)
        self.assertEqual(share["wrongControl"]["status"], 401)
        self.assertEqual(share["duplicateHeader"]["status"], 400)
        self.assertEqual(share["foreignOrigin"]["status"], 403)


if __name__ == "__main__":
    unittest.main()
