# -*- coding: utf-8 -*-
"""Rust S8 ops fixture freshness (ticket #57).

``tests/fixtures/rust_ops_rev1.json`` is generated by
``tests/generate_rust_ops_fixture.py`` from the real Python ledger reader,
Cloudflare checker, public DNS/TLS state machine and deployment assembly check.
The generator only uses temporary ledgers and injected DNS/TLS facts; it never
reads a production ledger, contacts the public network or runs a backup, restore,
update or rollback.
"""

import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests" / "fixtures" / "rust_ops_rev1.json"

sys.path.insert(0, str(ROOT / "tests"))


class RustOpsFixtureTests(unittest.TestCase):
    def test_fixture_is_fresh_from_the_real_python_tools(self):
        import generate_rust_ops_fixture as generator

        self.assertEqual(
            generator.generate(),
            json.loads(FIXTURE.read_text(encoding="utf-8")),
            "Rust ops fixture is stale; run "
            "python tests/generate_rust_ops_fixture.py",
        )

    def test_ledger_surface_records_every_acceptance_case(self):
        fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
        ledger = fixture["ledger"]
        self.assertTrue(fixture["metadata"]["fixture"])
        self.assertIn("inputs", ledger)
        for name in (
            "basic",
            "limit2",
            "limit0",
            "filtered",
            "today",
            "unattributed",
            "results",
            "missing",
            "empty",
            "truncated",
            "errors",
            "invalid",
        ):
            self.assertIn(name, ledger)
        for name in ("basic", "limit2", "cursor", "filters", "today", "limit200"):
            self.assertIn(name, ledger["requests"])
        self.assertEqual(ledger["missing"]["summary"]["coverage"]["ledgerPresent"], False)
        self.assertEqual(ledger["empty"]["summary"]["requests"], 0)
        self.assertEqual(ledger["truncated"]["summary"]["coverage"]["truncated"], True)
        self.assertEqual(ledger["basic"]["results"]["total"], 12)
        self.assertIn("legacy", ledger["basic"]["coverage"]["attributionReasons"])
        self.assertIn("summaryPrivate", ledger["errors"])
        self.assertEqual(
            len(ledger["invalid"]), 13,
            "every invalid filter must stay recorded",
        )

    def test_cloudflare_surface_records_every_acceptance_case(self):
        fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
        cloud = fixture["cloudflare"]
        self.assertIn("bothOk", cloud["dnsSources"])
        self.assertTrue(cloud["ingress"]["example"]["result"]["ok"])
        self.assertFalse(cloud["ingress"]["missingPath"]["result"]["ok"])
        self.assertEqual(cloud["ingress"]["invalidYaml"]["problemPrefix"], "invalid YAML:")
        self.assertEqual(cloud["ingress"]["unreadable"]["problemPrefix"], "config unreadable:")
        self.assertEqual(cloud["dnsAggregate"]["bothTimeout"]["state"], "timeout")
        self.assertEqual(cloud["dnsAggregate"]["bothNxdomain"]["state"], "nxdomain")
        self.assertEqual(cloud["dnsAggregate"]["truncated"]["addresses_truncated"], True)
        self.assertEqual(cloud["dnsAnswers"]["aAndAaaa"]["addresses"], ["8.8.8.8", "8.8.4.4"])
        self.assertEqual(cloud["negativeTtl"]["soa"], 60)
        self.assertEqual(cloud["summarize"]["allOkUnchecked"]["overall"], "degraded")
        self.assertEqual(cloud["summarize"]["allFailedUnchecked"]["overall"], "incomplete")
        self.assertEqual(cloud["exitCodes"]["notChecked"], 2)
        self.assertEqual(cloud["deadline"]["tooSmall"], 0.1)
        self.assertEqual(cloud["check"]["dnsTruncated"]["overall"], "degraded")
        self.assertEqual(cloud["check"]["dnsTruncated"]["reason"], "addresses_truncated")
        self.assertEqual(cloud["check"]["unchecked"]["overall"], "not_checked")


if __name__ == "__main__":
    unittest.main()
