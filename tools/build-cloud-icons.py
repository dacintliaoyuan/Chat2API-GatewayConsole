"""Export cloud-only console icons from the supplied artwork (requires Pillow)."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from PIL import Image


def main() -> None:
    gateway = Path(__file__).resolve().parents[1]
    source = gateway / "assets/cloud-console-icon-source/cutout.png"
    public = gateway / "web/public/icons/cloud"
    public.mkdir(parents=True, exist_ok=True)
    version = hashlib.sha256(source.read_bytes()).hexdigest()[:12]
    with Image.open(source) as original:
        source_size = list(original.size)
        image = original.convert("RGBA")
    alpha = image.getchannel("A")
    if alpha.getextrema()[0] != 0:
        raise ValueError("Cloud icon cutout must contain a transparent background")
    # Trim transparent padding only; retain white faces, clothing and highlights.
    box = alpha.getbbox()
    if box is None:
        raise ValueError("Cloud icon source contains no visible artwork")
    image = image.crop(box)
    side = max(image.size)
    padding = round(side * 0.025)
    square = Image.new("RGBA", (side + padding * 2, side + padding * 2), (0, 0, 0, 0))
    square.paste(image, ((square.width - image.width) // 2, (square.height - image.height) // 2))
    icon = square.resize((512, 512), Image.Resampling.LANCZOS)
    sizes = [(n, n) for n in (16, 24, 32, 48, 64, 96, 128, 256)]
    ico = gateway / "assets/UM云端控制台.ico"
    icon.save(ico, format="ICO", sizes=sizes)
    # A distinct path invalidates Explorer's previously cached opaque icon.
    (gateway / "assets/UM云端控制台-transparent.ico").write_bytes(ico.read_bytes())
    (public / "favicon.ico").write_bytes(ico.read_bytes())
    for name, size in (("icon-brand", 256), ("apple-touch-icon", 180), ("icon-192", 192), ("icon-512", 512)):
        icon.resize((size, size), Image.Resampling.LANCZOS).save(public / f"{name}.png")
    manifest = {
        "id": "/", "name": "UM 云端控制台", "short_name": "UM 云端",
        "start_url": "/#overview", "scope": "/", "display": "standalone",
        "icons": [{"src": f"/icons/cloud/icon-{size}.png?v={version}", "sizes": f"{size}x{size}", "type": "image/png"} for size in (192, 512)],
    }
    (public / "manifest.webmanifest").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    css = f'''/* Generated cloud-only brand; the environment status dot remains visible. */
.cloud-console .shell-env-name {{ position: relative; min-height: 40px; padding-left: 48px; }}
.cloud-console .shell-env-name::before {{ content: ""; position: absolute; top: 0; left: 0; width: 40px; height: 40px; background: transparent url("./icon-brand.png?v={version}") center / contain no-repeat; }}
.cloud-console .shell-env-mark {{ position: absolute; left: 30px; bottom: 0; width: 8px; height: 8px; border: 2px solid var(--md-surface); box-shadow: none; }}
.cloud-console .shell-env-sub {{ padding-left: 48px; }}
html[data-console-rail="collapsed"] .cloud-console .shell-env-name {{ width: 40px; padding-left: 0; }}
'''
    (public / "brand.css").write_text(css, encoding="utf-8")
    # Loaded only when the cloud console mounts; local branding stays intact.
    module = f'''// Generated by tools/build-cloud-icons.py; edit the source artwork or generator.
export function installCloudBrand(): void {{
  const links = [
    ['link[rel="icon"]', '/icons/cloud/favicon.ico?v={version}', 'icon'],
    ['link[rel="apple-touch-icon"]', '/icons/cloud/apple-touch-icon.png?v={version}', 'apple-touch-icon'],
    ['link[rel="manifest"]', '/icons/cloud/manifest.webmanifest?v={version}', 'manifest'],
    ['link[data-cloud-brand]', '/icons/cloud/brand.css?v={version}', 'stylesheet'],
  ] as const;
  for (const [selector, href, rel] of links) {{
    const link = document.querySelector<HTMLLinkElement>(selector) ?? document.createElement('link');
    link.rel = rel;
    link.href = href;
    if (rel === 'stylesheet') link.dataset.cloudBrand = '';
    if (!link.isConnected) document.head.append(link);
  }}
  document.title = 'UM 云端控制台';
}}
'''
    (gateway / "web/src/cloud/brand.ts").write_text(module, encoding="utf-8")
    print(json.dumps({"version": version, "source_size": source_size, "crop": box, "ico": str(ico)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
